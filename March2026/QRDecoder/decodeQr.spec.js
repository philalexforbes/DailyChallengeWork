const decodeQr = require('./decodeQr');

describe('Given a 6x6 matrix of binary data representing a QR code return the binary data in the code.', () => {
    test('1. decodeQr(["110011", "110011", "000000", "000000", "110000", "110001"]) should return "000000000000000000000001".', () => {
        expect(decodeQr(["110011", "110011", "000000", "000000", "110000", "110001"])).toEqual("000000000000000000000001");
    });
    test('2. decodeQr(["100011", "000011", "000000", "000000", "110011", "110011"]) should return "000000000000000000000001".', () => {
        expect(decodeQr(["100011", "000011", "000000", "000000", "110011", "110011"])).toEqual("000000000000000000000001");
    });
    test('3. decodeQr(["110011", "111111", "010000", "110000", "110011", "110100"]) should return "001101000011000000110100".', () => {
        expect(decodeQr(["110011", "111111", "010000", "110000", "110011", "110100"])).toEqual("001101000011000000110100");
    });
    test('4. decodeQr(["011011", "101011", "101000", "100010", "110011", "111011"]) should return "010001000100010101010110".', () => {
        expect(decodeQr(["011011", "101011", "101000", "100010", "110011", "111011"])).toEqual("010001000100010101010110");
    });
    test('5. decodeQr(["111100", "110001", "100011", "001101", "110011", "110011"]) should return "010000100100100101001110".', () => {
        expect(decodeQr(["111100", "110001", "100011", "001101", "110011", "110011"])).toEqual("010000100100100101001110");
    });
});