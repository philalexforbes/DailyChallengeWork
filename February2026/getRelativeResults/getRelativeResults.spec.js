const getRelativeResults = require('./getRelativeResults');

describe('Verify that the returned array shows the fastest time and then the time difference between each other times', () => {
    test('1. getRelativeResults(["1:25:32", "1:26:10", "1:27:05"]) should return ["0", "+0:38", "+1:33"].', () => {
        expect(getRelativeResults(["1:25:32", "1:26:10", "1:27:05"])).toEqual(["0", "+0:38", "+1:33"]);
    });
    test('2. getRelativeResults(["1:00:01", "1:00:05", "1:00:10"]) should return ["0", "+0:04", "+0:09"].', () => {
        expect(getRelativeResults(["1:00:01", "1:00:05", "1:00:10"])).toEqual(["0", "+0:04", "+0:09"]);
    });
    test('3. getRelativeResults(["1:10:06", "1:10:23", "1:10:48", "1:12:11"]) should return ["0", "+0:17", "+0:42", "+2:05"].', () => {
        expect(getRelativeResults(["1:10:06", "1:10:23", "1:10:48", "1:12:11"])).toEqual(["0", "+0:17", "+0:42", "+2:05"]);
    });
    test('4. getRelativeResults(["0:49:13", "0:49:15", "0:50:14", "0:51:30", "0:51:58", "0:52:16", "0:53:12", "0:53:31", "0:56:19", "1:02:20"]) should return ["0", "+0:02", "+1:01", "+2:17", "+2:45", "+3:03", "+3:59", "+4:18", "+7:06", "+13:07"].', () => {
        expect(getRelativeResults(["0:49:13", "0:49:15", "0:50:14", "0:51:30", "0:51:58", "0:52:16", "0:53:12", "0:53:31", "0:56:19", "1:02:20"]))
        .toEqual(["0", "+0:02", "+1:01", "+2:17", "+2:45", "+3:03", "+3:59", "+4:18", "+7:06", "+13:07"]);
    });
    test('5. getRelativeResults(["2:01:15", "2:10:45", "2:10:53", "2:11:04", "2:11:55", "2:13:27", "2:14:30", "2:15:10"]) should return ["0", "+9:30", "+9:38", "+9:49", "+10:40", "+12:12", "+13:15", "+13:55"].', () => {
        expect(getRelativeResults(["2:01:15", "2:10:45", "2:10:53", "2:11:04", "2:11:55", "2:13:27", "2:14:30", "2:15:10"])).toEqual(["0", "+9:30", "+9:38", "+9:49", "+10:40", "+12:12", "+13:15", "+13:55"]);
    });
})